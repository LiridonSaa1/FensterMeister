// Helper to convert a window spec into a company product
export function convertWindowToProduct(spec: HouseWindowSpec, customPrice?: number): Product {
  const sellPrice = customPrice || spec.basePriceUSD;
  const costPrice = Math.round(sellPrice * 0.55);
  return {
    id: `prod-win-${spec.id}`,
    name: spec.name,
    sku: `WIN-${spec.id.toUpperCase().replace(/_/g, '-')}`,
    description: `${spec.description} Includes ${spec.defaultMaterials[0]} frame, ${spec.defaultGlazing[0]}, multi-point locking hardware, and standard ${spec.standardSizes.widthRangeInches} sizing.`,
    purchasePrice: costPrice,
    sellingPrice: sellPrice,
    wholesalePrice: Math.round(sellPrice * 0.82),
    vatRate: 20,
    discount: 0,
    unit: 'unit',
    stock: 25,
    minStockAlert: 5,
    category: 'Windows & Glazing',
    type: 'product',
    status: 'active',
    svgKey: spec.svgKey,
    notes: `U-Factor: ${spec.energyEfficiency.uFactor} | SHGC: ${spec.energyEfficiency.shgc} | Energy Star: ${spec.energyEfficiency.energyStarRating}`,
    customSpecs: {
      'U-Factor': spec.energyEfficiency.uFactor,
      'SHGC': spec.energyEfficiency.shgc,
      'Sound STC': spec.energyEfficiency.stcRating,
      'Standard Dimensions': spec.standardSizes.widthRangeInches,
      'Energy Rating': spec.energyEfficiency.energyStarRating,
      'Opening Mechanism': spec.openingMechanism,
    },
    createdAt: new Date().toISOString(),
  };
}

// Helper to convert window spec into an invoice line item
export function convertWindowToInvoiceItem(
  spec: HouseWindowSpec,
  options?: {
    quantity?: number;
    material?: string;
    glazing?: string;
    widthInches?: number;
    heightInches?: number;
    customUnitPrice?: number;
    vatRate?: number;
  }
): InvoiceItem {
  const qty = options?.quantity || 1;
  const unitPrice = options?.customUnitPrice || spec.basePriceUSD;
  const material = options?.material || spec.defaultMaterials[0];
  const glazing = options?.glazing || spec.defaultGlazing[0];
  const dimensions = options?.widthInches && options?.heightInches 
    ? `${options.widthInches}"W × ${options.heightInches}"H` 
    : spec.standardSizes.widthRangeInches;

  const desc = `${spec.name} (${dimensions}) - Frame: ${material} | Glazing: ${glazing} | U-Factor: ${spec.energyEfficiency.uFactor}`;

  return {
    id: `item-win-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    productId: `prod-win-${spec.id}`,
    type: 'product',
    name: `${spec.name} [${dimensions}]`,
    description: desc,
    sku: `WIN-${spec.id.toUpperCase().slice(0, 8)}`,
    image: 'https://images.unsplash.com/photo-1503708998063-fb28b6dce510?auto=format&fit=crop&w=400&q=80',
    quantity: qty,
    unit: 'unit',
    unitPrice: unitPrice,
    discount: 0,
    discountType: 'percentage',
    vatRate: options?.vatRate || 20,
    total: qty * unitPrice,
  };
}
